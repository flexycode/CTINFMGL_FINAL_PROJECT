-- Supabase (PostgreSQL) Schema for Artificial Ledger Airlines

-- 1. Flights Table
CREATE TABLE IF NOT EXISTS public.flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_city TEXT NOT NULL,
    arrival_city TEXT NOT NULL,
    flight_date DATE NOT NULL,
    duration_hours INTEGER NOT NULL,
    base_price DECIMAL(10, 2) NOT NULL,
    flight_status TEXT NOT NULL CHECK (flight_status IN ('AVAILABLE', 'FULL', 'CANCELLED')) DEFAULT 'AVAILABLE',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Profiles (Extends Supabase Auth Users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users NOT NULL PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'user')) DEFAULT 'user',
    email TEXT UNIQUE NOT NULL,
    phone_number TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Seats Table
CREATE TABLE IF NOT EXISTS public.seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT REFERENCES public.flights(id) ON DELETE CASCADE NOT NULL,
    seat_number TEXT NOT NULL,
    class TEXT CHECK (class IN ('ECONOMY', 'PREMIUM ECONOMY', 'BUSINESS', 'FIRST')) NOT NULL,
    status TEXT CHECK (status IN ('AVAILABLE', 'BOOKED')) DEFAULT 'AVAILABLE' NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Carts Table
CREATE TABLE IF NOT EXISTS public.carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT REFERENCES public.flights(id) ON DELETE CASCADE NOT NULL,
    user_id UUID REFERENCES auth.users NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Flight Details / Regions
CREATE TABLE IF NOT EXISTS public.flight_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT REFERENCES public.flights(id) ON DELETE CASCADE NOT NULL,
    region TEXT NOT NULL,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.flights ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.seats ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.carts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.flight_details ENABLE ROW LEVEL SECURITY;

-- Basic Policies (Public read for flights/seats, User-specific for carts/profiles)
CREATE POLICY "Allow public read access to flights" ON public.flights FOR SELECT USING (true);
CREATE POLICY "Allow public read access to seats" ON public.seats FOR SELECT USING (true);
CREATE POLICY "Allow public read access to flight_details" ON public.flight_details FOR SELECT USING (true);

CREATE POLICY "Users can view own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can insert own profile" ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Users can update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Users can view own cart" ON public.carts FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can manage own cart" ON public.carts FOR ALL USING (auth.uid() = user_id);
